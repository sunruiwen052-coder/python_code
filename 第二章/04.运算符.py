# 逻辑运算符----> and  or  not
# 案例1:键盘输入一个整数,判断这个数是否在10-20之间--->在: True,不在: False
n = int(input("请输入一个整数:"))

print(f"{n}在10-20之间: ",n >= 10 and n <= 20) #and连接的条件是并且的关系,两个条件同时成立(True),结果才是True;否则,结果为False
print(f"{n}在10-20之间: ",10 <= n <= 20) 



# 案例2:键盘输入一个整数,判断这个数是否不在10-20之间
n = int(input("请输入一个整数:"))
print(f"{n}是否不在10-20之间: ",n<10 or n>20) #or连接的条件是或者的关系,其中一个条件符合,结果就是True