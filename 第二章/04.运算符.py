# 算术运算符 ： + — * / // % **
print("10 + 4 = ", 10 + 4) # 加
print("10 - 4 = ", 10 - 4) # 减
print("10 * 4 = ", 10 * 4) # 乘
print("10 / 4 = ", 10 / 4) # 除(结果为浮点数)
print("10 // 4 = ", 10 // 4) # 整除(结果为整数)
print("10 % 4 = ", 10 % 4) # 取余/求模
print("10 ** 4 = ", 10 ** 4) # 幂指数,10的4次方
# 括号里的双引号部分是字符串,直接输出,后面是计算式子,只输出结果


# 算数运算符的优先级--> **  --> * / // %  --> + -  (括号的优先级是最高的)
print("0.1 + 10 / 4**2 = ", 0.1 + 10 / 4**2)


